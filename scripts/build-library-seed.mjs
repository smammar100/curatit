// Builds supabase/seed.sql from the raw Apify exports in data/instagram/.
// Each dataset item is passed to private.ingest_instagram_post(), which splits
// it into the instagram_* tables (see the schema migration). Re-running the
// seed refreshes the scraped data in place. Each brand's chunk ends by queuing
// its posts for Creative Intelligence (CREATIVE_ANALYSIS_ENABLED=false leaves
// that out).
//
//   node scripts/build-library-seed.mjs

import fs from "node:fs";
import path from "node:path";
import { postImages, sources } from "./library-sources.mjs";

// The category slugs, read from src/lib/categories.ts (plain data, so a match is enough)
const CATEGORY_SLUGS = new Set(
  [...fs.readFileSync(path.join("src", "lib", "categories.ts"), "utf8").matchAll(/\{ slug: "([a-z0-9-]+)", name: /g)].map((m) => m[1])
);
// The 28 and Others (2026-10-29)
if (CATEGORY_SLUGS.size !== 29) throw new Error(`Expected 29 categories in src/lib/categories.ts, found ${CATEGORY_SLUGS.size}`);

// Dollar-quoted literal with a tag that can't appear in the data
const literal = (value) => {
  const text = typeof value === "string" ? value : JSON.stringify(value);
  let tag = "apify";
  while (text.includes(`$${tag}$`)) tag += "_";
  return `$${tag}$${text}$${tag}$`;
};
const q = (value) => (value === undefined || value === null ? "null" : `'${String(value).replaceAll("'", "''")}'`);

const out = ["-- Generated by scripts/build-library-seed.mjs from data/instagram/. Do not edit by hand.", ""];

// Creative Intelligence: the pipeline version new posts are queued under (src/lib/creative/versions.json)
const versions = JSON.parse(fs.readFileSync(path.join("src", "lib", "creative", "versions.json"), "utf8"));
const pipeline = `${versions.taxonomy}+${versions.prompt}`;
const queueAnalyses = process.env.CREATIVE_ANALYSIS_ENABLED !== "false";

for (const source of sources) {
  const { file, folder, categories, brand, brandAccounts } = source;
  const data = JSON.parse(fs.readFileSync(file, "utf8"));
  // The 28 categories come from a migration (…_app_categories) and src/lib/categories.ts
  for (const slug of categories) {
    if (!CATEGORY_SLUGS.has(slug)) throw new Error(`${brand.name}: "${slug}" isn't a category (src/lib/categories.ts)`);
  }
  const categoryId = (slug) => `(select id from public.categories where slug = ${q(slug)})`;
  const brandId = `(select id from public.brands where slug = ${q(brand.slug)})`;
  const runId = `(select id from public.scrape_runs where run_id = ${q(data.runId)})`;

  out.push(
    `-- ${brand.name}: ${data.items.length} posts from Apify run ${data.runId}`,
    "",
    // logos/<slug>.webp comes from scripts/download-brand-logos.mjs
    "insert into public.brands (name, slug, website_url, category_id, storage_folder, logo_path)",
    `values (${q(brand.name)}, ${q(brand.slug)}, ${q(brand.websiteUrl)}, ${categoryId(categories[0])}, ${q(folder)}, ${q(`logos/${brand.slug}.webp`)})`,
    "on conflict (slug) do update set name = excluded.name, website_url = excluded.website_url, category_id = excluded.category_id, storage_folder = excluded.storage_folder, logo_path = excluded.logo_path;",
    "",
    "insert into public.scrape_runs (actor, run_id, dataset_id, data_detail_level, target_url, item_count, scraped_at, notes)",
    `values (${q(data.actor)}, ${q(data.runId)}, ${q(data.datasetId)}, ${q(data.dataDetailLevel)}, ${q(data.source)}, ${data.items.length}, ${q(data.scrapedAt)}, ${q(data.note)})`,
    "on conflict (run_id) do update set item_count = excluded.item_count, notes = excluded.notes;",
    ""
  );

  for (const item of data.items) {
    // Paths in the library bucket (scripts/download-library-images.mjs uploads the files)
    const images = postImages(source, item);
    out.push(
      `-- ${item.url}`,
      `select private.ingest_instagram_post(${literal(item)}::jsonb, ${runId}, ${brandId});`,
      "insert into public.post_images (post_id, position, path) values",
      images.map((image, position) => `  (${q(item.id)}, ${position}, ${q(image.path)})`).join(",\n"),
      "on conflict (post_id, position) do update set path = excluded.path;",
      `delete from public.post_images where post_id = ${q(item.id)} and position >= ${images.length};`,
      // The brand's extra categories, on the post: the list in library-sources.mjs replaces
      // whatever tags the post had
      `delete from public.post_categories where post_id = ${q(item.id)};`,
      ...(categories.length > 1
        ? [
            `insert into public.post_categories (post_id, category_id) values ${categories
              .slice(1)
              .map((slug) => `(${q(item.id)}, ${categoryId(slug)})`)
              .join(", ")} on conflict do nothing;`,
          ]
        : []),
      ""
    );
  }

  out.push(
    `update public.instagram_accounts set brand_id = ${brandId}`,
    `where username in (${brandAccounts.map(q).join(", ")}) and brand_id is null;`,
    "",
    "-- These posts are in the library",
    "update public.instagram_posts set is_published = true, published_at = coalesce(published_at, now())",
    `where id in (${data.items.map((item) => q(item.id)).join(", ")});`,
    ""
  );

  // The batch is in: queue it for Creative Intelligence. creative_enqueue leaves out any post whose
  // images aren't all in Storage yet (the daily reconcile queues those later) and never queues the
  // same post, content and pipeline twice, so re-running a chunk is safe. Queuing costs nothing;
  // analyses run only when someone runs `npm run creative -- work`. A no-op before the migration.
  if (queueAnalyses) {
    out.push(
      "do $creative$",
      "begin",
      "  if to_regprocedure('public.creative_enqueue(text[], text, uuid, text, boolean, smallint)') is not null then",
      `    perform public.creative_enqueue(array[${data.items.map((item) => q(item.id)).join(", ")}], ${q(pipeline)}, ${runId}, 'import');`,
      "  end if;",
      "end",
      "$creative$;",
      ""
    );
  }
}

// Refresh planner statistics after the bulk load
out.push("analyze;", "");

fs.mkdirSync("supabase", { recursive: true });
fs.writeFileSync(path.join("supabase", "seed.sql"), out.join("\n"));
console.log("Wrote supabase/seed.sql");
